"""Agent PRs: turn what the traces taught into reviewable changes to the agents' own config.

Codex reads AGENTS.md, Claude reads CLAUDE.md. A proposal upserts one managed section
(between agentlens markers) in each, built from the playbook (verified items first) plus
evidence: support counts, votes, the latest held-out A/B, and judge findings that need a
human (tool setup / missing context). Proposals are versioned in ~/.agentlens/proposals (a
local git repo). apply() writes the files; open_pr() pushes a branch and opens a DRAFT PR
with gh. Both only run on explicit commands.
"""
import datetime
import difflib
import json
import os
from pathlib import Path
import shutil
import subprocess

import lessons as L

START='<!-- duo:lessons:start -->';END='<!-- duo:lessons:end -->'  # markers keep the old name so sections written before the rename still update
TARGETS={'codex':'AGENTS.md','claude':'CLAUDE.md'}

def home():return Path(os.environ.get('AGENTLENS_PROPOSALS') or Path.home()/'.agentlens'/'proposals').expanduser()
def index_path():return home()/'index.json'

def load_index():
    try:return json.loads(index_path().read_text())
    except (OSError,ValueError):return []

def save_index(items):
    home().mkdir(parents=True,exist_ok=True);index_path().write_text(json.dumps(items,indent=2))

def section(provider,items):
    lines=[START,'## Lessons from agentlens traces','',
           f'Auto-generated by agentlens from judged {provider.title()} runs. Each rule was proposed by blind judges reading real traces;',
           '"verified" = improved held-out replays (paired 95% CI above 0). Review before merging; edit freely outside the markers.','']
    for l in sorted(items,key=lambda x:(x.get('status')!='verified',-x.get('support_turns',0))):
        tag='verified' if l.get('status')=='verified' else f"{l.get('support_turns',0)} supporting turns"
        lines.append(f"- {l['rule']}  _({l.get('category','').replace('_',' ')} · {tag})_")
    lines+=['',END]
    return '\n'.join(lines)

def upsert(text,block):
    if START in text and END in text:
        a=text.index(START);b=text.index(END)+len(END)
        return text[:a]+block+text[b:]
    return (text.rstrip()+'\n\n' if text.strip() else '')+block+'\n'

def manual_findings(store,limit=8):
    """Judge fixes that need a human: tool setup / missing context."""
    if not store:return []
    ev=store.events_of_type('judge.action',5000)
    seen=set();out=[]
    for e in ev:
        if e.get('role') in ('tools','context') and e.get('rationale') not in seen:
            seen.add(e.get('rationale'));out.append({'provider':e.get('provider'),'target':e.get('role'),'rule':e.get('rationale')})
    return out[:limit]

def latest_evolve():
    runs=sorted((Path(os.environ.get('AGENTLENS_HOME') or Path.home()/'.agentlens').expanduser()/'replays').glob('*.json'))
    if len(runs)<2:return None
    try:
        import evalset
        a,b=[json.loads(r.read_text()) for r in runs[-2:]]
        if a['config'].get('no_lessons')==b['config'].get('no_lessons'):return None
        return {'from':a['started'],'to':b['started'],'compare':evalset.compare(a,b)}
    except (OSError,ValueError,KeyError):return None

def build(repo,store=None):
    repo=Path(repo).expanduser().resolve();items=L.ensure_ids(L.load())
    pid=datetime.datetime.now().strftime('%Y%m%d-%H%M%S');files=[]
    for provider,name in TARGETS.items():
        mine=[l for l in items if l['provider'] in (provider,'both') and l.get('target')!='workflow']
        if not mine:continue
        target=repo/name;old=target.read_text() if target.exists() else ''
        new=upsert(old,section(provider,mine))
        if new==old:continue
        diff=''.join(difflib.unified_diff(old.splitlines(True),new.splitlines(True),fromfile=f'a/{name}',tofile=f'b/{name}'))
        files.append({'provider':provider,'path':str(target),'name':name,'new':new,'diff':diff,'rules':len(mine)})
    if not files:return None
    ev=latest_evolve();manual=manual_findings(store)
    body=[f'# agentlens proposal {pid}','',f'Repo: `{repo}`','','## What changes']
    for f in files:body.append(f"- `{f['name']}` ({f['provider'].title()}): {f['rules']} rules in the managed agentlens section")
    if ev:
        body+=['','## Held-out A/B (lessons off → on)']
        for p,v in ev['compare']['models'].items():
            ci=v.get('ci') or [None,None]
            body.append(f"- {p.title()}: Δ {v.get('delta')} · paired 95% CI {ci[0]}…{ci[1]} · {'improved' if v.get('improved') else 'regressed' if v.get('regressed') else 'not significant'} (n={v.get('n')})")
    else:body+=['','_No held-out A/B yet: run `agentlens --evolve` to attach evidence before merging._']
    if manual:
        body+=['','## Needs a human (tool setup / missing context)']+[f"- [{m['provider']}] {m['target']}: {m['rule']}" for m in manual]
    proposal={'id':pid,'created':pid,'repo':str(repo),'status':'proposed','files':[{k:v for k,v in f.items() if k!='new'} for f in files],'evolve':ev,'url':None}
    d=home()/pid;d.mkdir(parents=True,exist_ok=True)
    for f in files:(d/(f['name']+'.patch')).write_text(f['diff']);(d/f['name']).write_text(f['new'])
    (d/'EVIDENCE.md').write_text('\n'.join(body)+'\n');(d/'proposal.json').write_text(json.dumps(proposal,indent=2))
    idx=load_index();idx.append({k:proposal[k] for k in ('id','created','repo','status','url')});save_index(idx)
    _commit(f'proposal {pid}')
    return proposal

def _commit(msg):
    """Version every proposal in the local proposals repo (never pushed)."""
    if not shutil.which('git'):return
    h=str(home())
    if not (home()/'.git').exists():subprocess.run(['git','init','-q',h],capture_output=True)
    subprocess.run(['git','-C',h,'add','-A'],capture_output=True)
    subprocess.run(['git','-C',h,'-c','user.name=agentlens','-c','user.email=agentlens@localhost','commit','-qm',msg],capture_output=True)

def get(pid):
    d=home()/pid
    return json.loads((d/'proposal.json').read_text()) if (d/'proposal.json').exists() else None

def set_status(pid,status,url=None):
    idx=load_index()
    for it in idx:
        if it['id']==pid:it['status']=status;it['url']=url or it.get('url')
    save_index(idx)
    p=get(pid)
    if p:p['status']=status;p['url']=url or p.get('url');(home()/pid/'proposal.json').write_text(json.dumps(p,indent=2))
    _commit(f'{pid}: {status}')

def apply(pid):
    p=get(pid)
    if not p:raise ValueError('unknown proposal '+pid)
    for f in p['files']:Path(f['path']).write_text((home()/pid/f['name']).read_text())
    set_status(pid,'applied');return [f['path'] for f in p['files']]

def open_pr(pid,run=subprocess.run):
    """Branch + commit + push + DRAFT PR in the target repo. Outward-facing: only on explicit --pr."""
    p=get(pid)
    if not p:raise ValueError('unknown proposal '+pid)
    repo=p['repo'];git=lambda *a:run(['git','-C',repo,*a],capture_output=True,text=True)
    if git('rev-parse','--is-inside-work-tree').returncode:raise RuntimeError(repo+' is not a git repository')
    if not shutil.which('gh'):raise RuntimeError('gh CLI not found')
    branch='agentlens/lessons-'+pid
    if git('checkout','-b',branch).returncode:raise RuntimeError('could not create branch '+branch)
    for f in p['files']:Path(f['path']).write_text((home()/pid/f['name']).read_text())
    git('add',*[f['name'] for f in p['files']])
    if git('commit','-m','Add lessons learned from agentlens traces').returncode:raise RuntimeError('commit failed')
    if git('push','-u','origin',branch).returncode:raise RuntimeError('push failed')
    out=run(['gh','pr','create','--draft','--title','Lessons learned from agentlens traces','--body-file',str(home()/pid/'EVIDENCE.md'),'--head',branch],
            cwd=repo,capture_output=True,text=True)
    if out.returncode:raise RuntimeError(out.stderr.strip() or 'gh pr create failed')
    url=out.stdout.strip().splitlines()[-1];set_status(pid,'pr_opened',url);return url

def render_list():
    idx=load_index()
    return '\n'.join(f"{p['id']}  {p['status']:<10} {p['repo']}{'  '+p['url'] if p.get('url') else ''}" for p in idx) or 'No proposals yet. agentlens --propose [REPO]'
